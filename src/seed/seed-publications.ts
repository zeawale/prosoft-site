const seed = async () => {
  const payload = await getPayload({ config })

  await payload.delete({
    context: { disableRevalidate: true },
    collection: 'publications',
    where: { id: { exists: true } },
  })

  for (const [index, { coverFile, ...item }] of PUBLICATIONS.entries()) {
    const cover = coverFile ? await seedMedia(payload, coverFile, item.title) : undefined
    await payload.create({
      context: { disableRevalidate: true },
      collection: 'publications',
      data: { ...item, cover, order: index, showOnHome: true },
    })
  }

  console.log(`Публикации: ${PUBLICATIONS.length}`)
  process.exit(0)
}

await seed()
